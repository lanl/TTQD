

r"""
MPO constructors
----------------

This module contains two related fermionic MPO constructions.

The spinful one-dimensional Hubbard constructor represents each lattice site
with the four-state basis

.. math::

    |0\rangle,\quad |\uparrow\rangle,\quad |\downarrow\rangle,\quad
    |\uparrow\downarrow\rangle,

and builds a nearest-neighbor finite-state MPO for the local-operator form

.. math::

    H_{\mathrm{Hub,MPO}} =
    U \sum_i n_{i\uparrow} n_{i\downarrow}
    + t \sum_i \Big[
        c^\dagger_{i\uparrow}\widetilde c_{i+1,\uparrow}
        + c^\dagger_{i\downarrow}\widetilde c_{i+1,\downarrow}
        - c_{i\uparrow}\widetilde c^\dagger_{i+1,\uparrow}
        - c_{i\downarrow}\widetilde c^\dagger_{i+1,\downarrow}
      \Big],

where :math:`\widetilde c_{i\sigma}=c_{i\sigma}P_i` and
:math:`P_i=(-1)^{n_{i\uparrow}+n_{i\downarrow}}`.  This is the finite-state
MPO representation of nearest-neighbor Hubbard hopping in the local spinful
site basis; the sign convention is set by the input hopping parameter ``t``.

The ab initio/quantum-chemistry constructors start from one- and two-electron
spin-orbital integrals,

.. math::

    H =
    \sum_{pq} h_{pq} a^\dagger_p a_q
    + {1 \over 2}\sum_{pqrs} h_{pqrs}
      a^\dagger_p a^\dagger_q a_r a_s,

then:

1. map each fermionic monomial to a Jordan-Wigner product of local operators;
2. collect identical local operator strings and their scalar coefficients;
3. encode the resulting sum of product operators as an exact open-boundary MPO.

The generic construction uses a prefix tree/finite-state-machine layout, which
is standard MPO practice :cite:`Hubig:2017gc`.  The compact constructor uses the
same exact local strings but reuses both left and right substrings through
fork/merge bond labels.
"""

