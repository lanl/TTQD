@dataclass(frozen=True)
class BondLabel:
    """
    Meaning of one MPO bond state.

    kind:
      START : left boundary
      STOP  : right boundary
      CONST : constant-operator propagation channel
      L     : fork label = operators already applied on the left
      R     : merge label = operators still to be applied on the right

    payload:
      tuple of (site_index, mat_key) pairs
    """
    kind: str
    payload: Tuple[Tuple[int, Tuple[complex, ...]], ...] = ()


def _collect_local_term_strings(h1, h2, tol=1e-14, dtype=np.complex128):
    r"""
    Collect unique local JW operator strings for

    .. math::

        H =
        \sum_{pq} h_{pq} a_p^\dagger a_q
        + {1 \over 2}\sum_{pqrs} h_{pqrs}
          a_p^\dagger a_q^\dagger a_r a_s.

    This is the common front-end used by the generic and compact chemistry MPO
    builders.  It performs the Jordan-Wigner transformation, drops zero
    nilpotent strings, and combines duplicate product operators.

    Returns
    -------
    term_strings : list[tuple[complex, list[np.ndarray]]]
        Each item is (coeff, local_ops), where local_ops[i] is the 2x2
        operator on site i for one full term string.
    """
    h1 = np.asarray(h1, dtype=dtype)
    h2 = np.asarray(h2, dtype=dtype)

    if h1.ndim != 2 or h1.shape[0] != h1.shape[1]:
        raise ValueError("h1 must have shape (K, K)")
    K = h1.shape[0]

    if h2.shape != (K, K, K, K):
        raise ValueError("h2 must have shape (K, K, K, K)")

    path_coeff = defaultdict(complex)

    def add_term(coeff, fermion_ops):
        coeff = complex(coeff)
        if abs(coeff) < tol:
            return

        local = jw_local_string(K, fermion_ops, dtype=dtype)

        # Drop nilpotent terms, e.g. c^2 = 0
        if any(np.all(np.abs(op) < tol) for op in local):
            return

        path = tuple(_mat_key(op, tol=tol) for op in local)
        # print("debug: path = ", path)
        path_coeff[path] += coeff

    # one-body terms
    for p, q in np.argwhere(np.abs(h1) > tol):
        add_term(h1[p, q], [(p, True), (q, False)])

    # two-body terms
    for p, q, r, s in np.argwhere(np.abs(h2) > tol):
        add_term(0.5 * h2[p, q, r, s],
                 [(p, True), (q, True), (r, False), (s, False)])

    term_strings = []
    for path, coeff in path_coeff.items():
        if abs(coeff) <= tol:
            continue
        local_ops = [_key_to_mat(key) for key in path]
        term_strings.append((coeff, local_ops))

    return term_strings


def _nonidentity_pairs(local_ops, tol=1e-14):
    """
    Return the non-identity local operators of a term as
    ((site, mat_key), ...).
    """
    d = local_ops[0].shape[0]
    Ikey = _mat_key(np.eye(d, dtype=np.complex128), tol=tol)

    pairs = []
    for i, op in enumerate(local_ops):
        key = _mat_key(op, tol=tol)
        if key != Ikey:
            pairs.append((i, key))
    return tuple(pairs)


def _bond_label_for_term(pairs, bond, switch_site, n_sites):
    """
    Label on a given bond for one term.

    bond = 0..n_sites
    """
    if bond == 0:
        return BondLabel("START")
    if bond == n_sites:
        return BondLabel("STOP")

    if bond <= switch_site:
        # fork label: identify what has already been applied on the left
        left_payload = tuple((pos, key) for pos, key in pairs if pos < bond)
        return BondLabel("L", left_payload)

    # merge label: identify what remains to be applied on the right
    right_payload = tuple((pos, key) for pos, key in pairs if pos >= bond)
    return BondLabel("R", right_payload)


def _label_sort_key(label: BondLabel):
    kind_order = {
        "START": 0,
        "CONST": 1,
        "L": 2,
        "R": 3,
        "STOP": 4,
    }
    return (kind_order.get(label.kind, 99), repr(label.payload))


def build_compact_second_quantized_mpo(
    h1,
    h2,
    constant=0.0,
    tol=1e-14,
    dtype=np.complex128,
):
    r"""
    Build a compact, exact, open-boundary MPO for

    .. math::

        H = C_0 I
        + \sum_{pq} h_{pq} a_p^\dagger a_q
        + {1 \over 2}\sum_{pqrs} h_{pqrs}
          a_p^\dagger a_q^\dagger a_r a_s,

    where :math:`C_0` is a constant shift.

    It starts from the same local-string expansion as
    :func:`second_quantized_to_mpo`,

    .. math::

        H-C_0I =
        \sum_\ell \alpha_\ell
        O^{(\ell)}_0 \otimes O^{(\ell)}_1 \otimes \cdots
        \otimes O^{(\ell)}_{K-1},

    but stores a term on bond :math:`b` by either its already-applied left
    substring or its still-needed right substring.  For each term, a
    ``switch_site`` near the middle of the non-identity support is chosen; the
    scalar coefficient :math:`\alpha_\ell` is placed only on that site.  Shared
    left and right substrings are then reused across many terms, giving a
    smaller exact MPO than the pure prefix tree in many dense ab initio cases.

    Returns
    -------
    Ws : list[np.ndarray]
        Ws[i] has shape (D_i, D_{i+1}, 2, 2), with true OBC:
        Ws[0].shape[0]  == 1
        Ws[-1].shape[1] == 1

    bond_labels : list[list[BondLabel]]
        bond_labels[b] is the list of bond states on bond b, b = 0..K.
        The tensor Ws[i][a, b] maps
        bond_labels[i][a] -> bond_labels[i+1][b].
    """
    h1 = np.asarray(h1, dtype=dtype)
    h2 = np.asarray(h2, dtype=dtype)

    if h1.ndim != 2 or h1.shape[0] != h1.shape[1]:
        raise ValueError("h1 must have shape (K, K)")
    K = h1.shape[0]

    # TODO: use chols to reduce memeory
    if h2.shape != (K, K, K, K):
        raise ValueError("h2 must have shape (K, K, K, K)")

    I2 = np.eye(2, dtype=dtype)

    # States living on each bond 0..K
    bond_state_sets = [set() for _ in range(K + 1)]
    bond_state_sets[0].add(BondLabel("START"))
    bond_state_sets[K].add(BondLabel("STOP"))

    # edge_ops[i][(left_label, right_label)] = 2x2 local operator block
    edge_ops = [dict() for _ in range(K)]

    def add_edge(site, left_label, right_label, op, *, accumulate):
        key = (left_label, right_label)

        if key not in edge_ops[site]:
            edge_ops[site][key] = np.array(op, copy=True)
            return

        if accumulate:
            edge_ops[site][key] += op
            return

        old = edge_ops[site][key]
        if not np.allclose(old, op, atol=tol, rtol=0.0):
            raise RuntimeError(
                f"Bond-label collision on non-switch edge at site {site}: "
                f"{left_label} -> {right_label}. "
                "This means the label set is too coarse for this edge."
            )
        # Shared substring: keep only one copy, do not sum.

    # Build all non-constant term strings
    term_strings = _collect_local_term_strings(h1, h2, tol=tol, dtype=dtype)
    print("\nDebug: number of local term string: ", len(term_strings))

    # Accumulate exact compact transitions
    for coeff, local_ops in term_strings:
        pairs = _nonidentity_pairs(local_ops, tol=tol)

        # If a term collapses to pure identity, absorb it into the constant
        if len(pairs) == 0:
            constant += coeff
            continue

        # Switch after the "middle" non-identity operator.
        # For 1,2,3,4 non-identity sites this gives ranks 0,0,1,1 respectively,
        # so each label stores at most two non-identity operators on one side.
        switch_rank = (len(pairs) - 1) // 2
        switch_site = pairs[switch_rank][0]

        for bond in range(K + 1):
            bond_state_sets[bond].add(
                _bond_label_for_term(pairs, bond, switch_site, K)
            )

        for site in range(K):
            left_label = _bond_label_for_term(pairs, site, switch_site, K)
            right_label = _bond_label_for_term(pairs, site + 1, switch_site, K)
            print(f"\nleft_label  [{site}] ", left_label)
            print(f"right_label [{site}] ", right_label)
            print(f"local_ops   [{site}] ", local_ops[site])

            if site == switch_site:
                # Put the scalar coefficient on exactly one site.
                add_edge(
                    site,
                    left_label,
                    right_label,
                    coeff * local_ops[site],
                    accumulate=True,
                )
            else:
                # Shared prefix/suffix edge: keep once, do not sum.
                add_edge(
                    site,
                    left_label,
                    right_label,
                    local_ops[site],
                    accumulate=False,
                )

    # Optional constant term
    if abs(constant) > tol:
        if K == 1:
            add_edge(
                0,
                BondLabel("START"),
                BondLabel("STOP"),
                constant * I2,
                accumulate=True,
            )
        else:
            const_label = BondLabel("CONST")
            for bond in range(1, K):
                bond_state_sets[bond].add(const_label)

            add_edge(
                0,
                BondLabel("START"),
                const_label,
                constant * I2,
                accumulate=True,
            )
            for site in range(1, K - 1):
                add_edge(
                    site,
                    const_label,
                    const_label,
                    I2,
                    accumulate=False,
                )
            add_edge(
                K - 1,
                const_label,
                BondLabel("STOP"),
                I2,
                accumulate=False,
            )

    # Enumerate states on each bond
    bond_labels = []
    bond_index = []
    for bond in range(K + 1):
        labels = sorted(bond_state_sets[bond], key=_label_sort_key)
        bond_labels.append(labels)
        bond_index.append({lab: i for i, lab in enumerate(labels)})

    # True OBC sanity checks
    if bond_labels[0] != [BondLabel("START")]:
        raise RuntimeError("Left boundary is not one-dimensional.")
    if bond_labels[-1] != [BondLabel("STOP")]:
        raise RuntimeError("Right boundary is not one-dimensional.")

    # Build dense local MPO tensors
    Ws = []
    for site in range(K):
        Dl = len(bond_labels[site])
        Dr = len(bond_labels[site + 1])
        W = np.zeros((Dl, Dr, 2, 2), dtype=dtype)

        for (left_label, right_label), op in edge_ops[site].items():
            a = bond_index[site][left_label]
            b = bond_index[site + 1][right_label]
            W[a, b] += op

        W[np.abs(W) < tol] = 0.0
        Ws.append(W)

    return Ws, bond_labels

