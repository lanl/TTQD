def _kron_all(local_ops):
    out = np.array([[1.0]], dtype=np.complex128)
    for op in local_ops:
        out = np.kron(out, op)
    return out


def _dense_ladder_operators(n_sites, dtype=np.complex128):
    # I, F, c, _ = _site_ops(dtype=dtype)

    ops = local_fermion_ops(dtype)
    I = ops["I"]
    F = ops["F"]
    c = ops["c"]

    a_ops = []
    for p in range(n_sites):
        local = []
        for i in range(n_sites):
            if i < p:
                local.append(F)
            elif i == p:
                local.append(c)
            else:
                local.append(I)
        a_p = _kron_all(local)
        a_ops.append(a_p)
    adag_ops = [a.conj().T for a in a_ops]
    return a_ops, adag_ops


def _dense_hamiltonian_from_integrals(h1, h2, tol=1e-14, dtype=np.complex128):
    h1 = np.asarray(h1, dtype=dtype)
    h2 = np.asarray(h2, dtype=dtype)
    n_sites = h1.shape[0]
    dim = 2 ** n_sites
    H = np.zeros((dim, dim), dtype=dtype)
    a_ops, adag_ops = _dense_ladder_operators(n_sites, dtype=dtype)

    for p, q in np.argwhere(np.abs(h1) > tol):
        H += h1[p, q] * (adag_ops[p] @ a_ops[q])

    for p, q, r, s in np.argwhere(np.abs(h2) > tol):
        H += 0.5 * h2[p, q, r, s] * (adag_ops[p] @ adag_ops[q] @ a_ops[r] @ a_ops[s])

    return H


def _dense_from_mpo(Ws, tol=1e-14, dtype=np.complex128):
    partial = {0: np.array([[1.0]], dtype=dtype)}
    for i, W in enumerate(Ws):
        _, Dr, _, _ = W.shape
        nxt = {}
        for a, left in partial.items():
            for b in range(Dr):
                block = W[a, b]
                if np.max(np.abs(block)) <= tol:
                    continue
                term = np.kron(left, block)
                if b in nxt:
                    nxt[b] += term
                else:
                    nxt[b] = term
        if not nxt:
            raise RuntimeError(f"MPO has no active transitions at site {i}")
        partial = nxt

    if 0 not in partial:
        raise RuntimeError("Final MPO bond does not contain sink index 0")

    return partial[0]


def _n2_pyscf_spin_orbital_integrals(active_spatial_orbitals=2, bond_length_angstrom=1.1):
    try:
        from pyscf import gto, scf, ao2mo
    except ImportError as exc:
        raise ImportError("PySCF is required for the N2 test. Install with: pip install pyscf") from exc

    mol = gto.Mole()
    mol.atom = f"N 0.0 0.0 0.0; N 0.0 0.0 {bond_length_angstrom}"
    mol.unit = "Angstrom"
    mol.basis = "sto-3g"
    mol.spin = 0
    mol.charge = 0
    mol.verbose = 0
    mol.build()

    mf = scf.RHF(mol)
    mf.conv_tol = 1e-12
    mf.kernel()
    if not mf.converged:
        raise RuntimeError("PySCF RHF did not converge for N2 test.")

    C = mf.mo_coeff
    n_mo = C.shape[1]
    if active_spatial_orbitals > n_mo:
        raise ValueError(
            f"Requested {active_spatial_orbitals} active orbitals but only {n_mo} MOs available."
        )

    hcore_ao = mf.get_hcore()
    h1_mo = C.T @ hcore_ao @ C

    eri_mo = ao2mo.restore(1, ao2mo.kernel(mol, C), n_mo)

    idx = np.arange(active_spatial_orbitals)
    h1_spatial = h1_mo[np.ix_(idx, idx)]
    eri_spatial = eri_mo[np.ix_(idx, idx, idx, idx)]

    n_spin = 2 * active_spatial_orbitals
    h1 = np.zeros((n_spin, n_spin), dtype=np.complex128)
    h2 = np.zeros((n_spin, n_spin, n_spin, n_spin), dtype=np.complex128)

    for p in range(active_spatial_orbitals):
        for q in range(active_spatial_orbitals):
            h1[2 * p, 2 * q] = h1_spatial[p, q]
            h1[2 * p + 1, 2 * q + 1] = h1_spatial[p, q]

    # Spin-orbital two-electron tensor for operator order a_p^† a_q^† a_r a_s
    # using spin-conserving Coulomb integrals from the RHF spatial MO basis.
    h2[0::2, 0::2, 0::2, 0::2] = eri_spatial  # sigma=0, tau=0
    h2[0::2, 1::2, 1::2, 0::2] = eri_spatial  # sigma=0, tau=1
    h2[1::2, 0::2, 0::2, 1::2] = eri_spatial  # sigma=1, tau=0
    h2[1::2, 1::2, 1::2, 1::2] = eri_spatial  # sigma=1, tau=1

    return h1, h2

def _test_second_quantized_to_mpo_with_n2():
    tol = 1e-12
    h1, h2 = _n2_pyscf_spin_orbital_integrals(active_spatial_orbitals=2, bond_length_angstrom=1.1)
    Ws = second_quantized_to_mpo(h1, h2, tol=tol, dtype=np.complex128)

