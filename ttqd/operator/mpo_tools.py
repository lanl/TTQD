def local_fermion_ops(dtype=np.complex128):
    r"""
    Return local Jordan-Wigner operators for one spin orbital.

    Each ab initio MPO site is one spin orbital with basis
    :math:`|0\rangle, |1\rangle`.  The local matrices are

    .. math::

        I =
        \begin{pmatrix}1&0\\0&1\end{pmatrix},\qquad
        F = (-1)^n =
        \begin{pmatrix}1&0\\0&-1\end{pmatrix},

    .. math::

        c =
        \begin{pmatrix}0&1\\0&0\end{pmatrix},\qquad
        c^\dagger =
        \begin{pmatrix}0&0\\1&0\end{pmatrix},\qquad
        n = c^\dagger c.

    The global fermionic operator on site :math:`p` is represented by a
    Jordan-Wigner string,

    .. math::

        a_p = F_0 F_1 \cdots F_{p-1} c_p,\qquad
        a^\dagger_p = F_0 F_1 \cdots F_{p-1} c^\dagger_p.
    """
    I = np.eye(2, dtype=dtype)
    F = np.array([[1, 0],
                  [0, -1]], dtype=dtype)          # parity
    c = np.array([[0, 1],
                  [0, 0]], dtype=dtype)           # annihilation
    cd = np.array([[0, 0],
                   [1, 0]], dtype=dtype)          # creation
    n = cd @ c
    zc = np.zeros((2, 2), dtype=dtype)
    return {
        "I": I,
        "F": F,
        "c": c,
        "cd": cd,
        "n": n,
        "0": zc,
    }


def _mat_key(mat, tol=1e-14):
    """
    Hashable key for a 2x2 matrix.
    """
    m = np.array(mat, dtype=np.complex128, copy=True)
    m[np.abs(m) < tol] = 0.0
    return tuple(m.ravel())


def _key_to_mat(key):
    return np.array(key, dtype=np.complex128).reshape(2, 2)


def jw_local_string(n_sites, ops, dtype=np.complex128):
    r"""
    Convert a fermionic monomial to a list of local 2x2 operators
    using Jordan-Wigner strings.

    For a monomial in the explicit operator order

    .. math::

        M = a^\sharp_{p_1} a^\sharp_{p_2}\cdots a^\sharp_{p_m},

    where :math:`\sharp` means either creation or annihilation, this routine
    multiplies the corresponding local Jordan-Wigner factors site by site:

    .. math::

        M \mapsto O_0 \otimes O_1 \otimes \cdots \otimes O_{K-1}.

    Repeated operators on the same site are multiplied locally in the same
    order as the fermionic monomial.  Nilpotent products such as
    :math:`c_p c_p = 0` therefore become a zero local operator and are later
    dropped by the MPO builders.

    Parameters
    ----------
    n_sites : int
    ops : list[tuple[int, bool]]
        [(site, dagger), ...] in the exact operator order appearing
        in the monomial.
        dagger=True  -> a^\dagger_site
        dagger=False -> a_site

    Returns
    -------
    local_ops : list[np.ndarray]
        local_ops[i] is the 2x2 operator acting on site i.
    """
    site_ops = local_fermion_ops(dtype)
    I = site_ops["I"]
    F = site_ops["F"]
    c = site_ops["c"]
    cd = site_ops["cd"]
    local = [I.copy() for _ in range(n_sites)]

    for site, dagger in ops:
        if not (0 <= site < n_sites):
            raise IndexError(f"site {site} out of range for n_sites={n_sites}")

        # Jordan-Wigner parity string on all earlier sites
        for j in range(site):
            local[j] = local[j] @ F

        # Local ladder operator
        local[site] = local[site] @ (cd if dagger else c)

    return local


def second_quantized_to_mpo(h1, h2, tol=1e-14, dtype=np.complex128):
    r"""
    Build an exact prefix-tree MPO for a spin-orbital ab initio Hamiltonian.

    .. math::

        H =
        \sum_{pq} h_{pq} a_p^\dagger a_q
        + {1 \over 2}\sum_{pqrs} h_{pqrs}
          a_p^\dagger a_q^\dagger a_r a_s.

    ``h1`` stores :math:`h_{pq}` and ``h2`` stores :math:`h_{pqrs}` in the
    same operator order used in the equation.  Each nonzero integral contributes
    one fermionic monomial,

    .. math::

        h_{pq} a^\dagger_p a_q,\qquad
        {1 \over 2} h_{pqrs} a^\dagger_p a^\dagger_q a_r a_s,

    which is converted to a local Jordan-Wigner string

    .. math::

        \alpha_\ell\,
        O^{(\ell)}_0 \otimes O^{(\ell)}_1 \otimes \cdots
        \otimes O^{(\ell)}_{K-1}.

    Identical local strings are summed before the MPO is built.  The prefix-tree
    construction creates one virtual state for each distinct prefix
    :math:`(O^{(\ell)}_0,\ldots,O^{(\ell)}_{i-1})`.  A path through the MPO is

    .. math::

        \emptyset
        \xrightarrow{O^{(\ell)}_0}
        (O^{(\ell)}_0)
        \xrightarrow{O^{(\ell)}_1}
        \cdots
        \xrightarrow{\alpha_\ell O^{(\ell)}_{K-1}}
        \mathrm{sink},

    so contracting all tensors sums exactly over all Hamiltonian product
    strings.

    Parameters
    ----------
    h1 : (K,K) ndarray
        One-electron integral tensor :math:`h_{pq}`.
    h2 : (K,K,K,K) ndarray
        Two-electron tensor :math:`h_{pqrs}` in the order
        :math:`a^\dagger_p a^\dagger_q a_r a_s`.
    tol : float
        Numerical threshold for dropping tiny terms.
    dtype : numpy dtype

    Returns
    -------
    Ws : list[np.ndarray]
        Ws[i] has shape (D_left_i, D_right_i, 2, 2).
        The Hamiltonian is reconstructed as the MPO contraction of this list.
    """
    h1 = np.asarray(h1, dtype=dtype)
    h2 = np.asarray(h2, dtype=dtype)

    if h1.ndim != 2 or h1.shape[0] != h1.shape[1]:
        raise ValueError("h1 must have shape (K,K)")
    K = h1.shape[0]

    # TODO: use chols to reduce memeory
    if h2.shape != (K, K, K, K):
        raise ValueError("h2 must have shape (K,K,K,K)")

    # path_coeff[path] = coefficient for one full local operator string
    # A path is a tuple of K matrix-keys, one for each site.
    path_coeff = defaultdict(complex)

    def add_term(coeff, fermion_ops):
        coeff = complex(coeff)
        if abs(coeff) < tol:
            return

        local = jw_local_string(K, fermion_ops, dtype=dtype)

        # Nilpotent cases (e.g. c^2 = 0) lead to a zero local operator somewhere.
        if any(np.all(np.abs(op) < tol) for op in local):
            return

        #for op in local:
        #    print("op = ", op)
        path = tuple(_mat_key(op, tol=tol) for op in local)
        path_coeff[path] += coeff

    # One-body terms
    for p, q in np.argwhere(np.abs(h1) > tol):
        add_term(h1[p, q], [(p, True), (q, False)])

    # Two-body terms
    # The Hamiltonian in the user's formula has the prefactor 1/2 outside the sum.
    for p, q, r, s in np.argwhere(np.abs(h2) > tol):
        # print("\ndebug: pqrs = ", p, q, r, s)
        add_term(0.5 * h2[p, q, r, s],
                 [(p, True), (q, True), (r, False), (s, False)])
    # exit()

    # Remove cancellations
    path_coeff = {path: coeff for path, coeff in path_coeff.items()
                  if abs(coeff) > tol}

    # Zero Hamiltonian -> trivial zero MPO
    if not path_coeff:
        return [np.zeros((1, 1, 2, 2), dtype=dtype) for _ in range(K)]

    # Special case K=1
    if K == 1:
        W = np.zeros((1, 1, 2, 2), dtype=dtype)
        for path, coeff in path_coeff.items():
            W[0, 0] += coeff * _key_to_mat(path[0])
        W[np.abs(W) < tol] = 0.0
        return [W]

    # prefix_layers[d] maps a prefix of length d to its bond index at layer d
    # layer 0 contains only the empty prefix
    prefix_layers = [{(): 0}] + [dict() for _ in range(K - 1)]

    # transitions[i][(a,b)] = local 2x2 operator on site i connecting
    # bond state a at layer i to bond state b at layer i+1
    transitions = [dict() for _ in range(K)]

    for path, coeff in path_coeff.items():
        prefix = ()

        # Sites 0..K-2 create / follow prefix-tree states
        for i in range(K - 1):
            cur_idx = prefix_layers[i][prefix]

            next_prefix = prefix + (path[i],)
            next_layer = prefix_layers[i + 1]
            if next_prefix not in next_layer:
                next_layer[next_prefix] = len(next_layer)
            next_idx = next_layer[next_prefix]

            op = _key_to_mat(path[i])

            # This edge may be revisited by many different full strings that share the prefix.
            old = transitions[i].get((cur_idx, next_idx))
            if old is None:
                transitions[i][(cur_idx, next_idx)] = op
            else:
                # Shared prefix: the edge operator should be identical, not accumulated.
                if not np.allclose(old, op, atol=tol, rtol=0.0):
                    raise RuntimeError("Internal inconsistency in prefix-tree construction.")

            prefix = next_prefix

        # Last site goes to a single sink state of dimension 1
        cur_idx = prefix_layers[K - 1][prefix]
        last_op = coeff * _key_to_mat(path[K - 1])

        if (cur_idx, 0) in transitions[K - 1]:
            transitions[K - 1][(cur_idx, 0)] += last_op
        else:
            transitions[K - 1][(cur_idx, 0)] = last_op

    # Build the actual MPO tensors
    dims_left = [len(prefix_layers[i]) for i in range(K)]
    dims_right = [len(prefix_layers[i + 1]) for i in range(K - 1)] + [1]

    Ws = []
    for i in range(K):
        W = np.zeros((dims_left[i], dims_right[i], 2, 2), dtype=dtype)
        for (a, b), op in transitions[i].items():
            W[a, b] += op
        W[np.abs(W) < tol] = 0.0
        Ws.append(W)

    return Ws



